export function evaluateItemMatchesRule(item, rule) {
  if (!item || !rule) return true;
  const { field, op, value, compareField, valueMin, valueMax } = rule;
  if (!field) return true;

  const itemVal = item[field];
  if (itemVal === null || itemVal === undefined) return false;

  // Support array contains (e.g. predictive_setups array)
  if (Array.isArray(itemVal)) {
    if (op === 'contains' || op === '==') {
      const targetStr = String(value || '').toLowerCase();
      return itemVal.some((el) => String(el).toLowerCase() === targetStr || String(el).toLowerCase().includes(targetStr));
    }
    return false;
  }

  // Compare against another column field if compareField is specified
  if (compareField) {
    const targetVal = item[compareField];
    if (targetVal === null || targetVal === undefined) return false;
    const numA = _toNumber(itemVal);
    const numB = _toNumber(targetVal);
    if (!isNaN(numA) && !isNaN(numB)) {
      if (op === '>') return numA > numB;
      if (op === '<') return numA < numB;
      if (op === '>=') return numA >= numB;
      if (op === '<=') return numA <= numB;
      if (op === '==') return numA === numB;
      if (op === '!=') return numA !== numB;
    }
    return false;
  }

  // Range comparison (between)
  if (op === 'between') {
    const num = _toNumber(itemVal);
    const min = Number(valueMin);
    const max = Number(valueMax);
    if (isNaN(num)) return false;
    if (!isNaN(min) && num < min) return false;
    if (!isNaN(max) && num > max) return false;
    return true;
  }

  // Numeric comparison (with fraction parsing for fields like confirmation_count)
  const numVal = _toNumber(itemVal);
  const targetNum = Number(value);

  if (!isNaN(numVal) && !isNaN(targetNum) && value !== '' && value !== null && value !== undefined) {
    if (op === '>') return numVal > targetNum;
    if (op === '<') return numVal < targetNum;
    if (op === '>=') return numVal >= targetNum;
    if (op === '<=') return numVal <= targetNum;
    if (op === '==') return numVal === targetNum;
    if (op === '!=') return numVal !== targetNum;
  }

  // Fallback to string comparison
  const strA = String(itemVal).toLowerCase();
  const strB = String(value || '').toLowerCase();
  if (op === '==') return strA === strB;
  if (op === '!=') return strA !== strB;
  if (op === 'contains') return strA.includes(strB);

  return true;
}

/**
 * Parse a value to a number, including fraction strings like "6/8" → 6.
 * For fraction strings, returns the numerator for numeric comparisons.
 */
function _toNumber(val) {
  if (val === null || val === undefined) return NaN;
  if (typeof val === 'number') return val;
  if (typeof val === 'string' && val.includes('/')) {
    const parts = val.split('/');
    if (parts.length === 2) {
      const num = Number(parts[0].trim());
      if (!isNaN(num)) return num;
    }
  }
  return Number(val);
}

